#include <iostream>
# include <cmath>    // 提供 std::fabs 函数，用于计算浮点数的绝对值
// 正确做法：判断差值是否足够小。
bool areAlmostEqual(double a, double b, double epsilon = 1e-9) {
    return std::fabs(a - b) < epsilon;  // 如果差值的绝对值小于 epsilon，则认为两个浮点数足够接近
}


